export const fill = (s: string, vars?: Record<string, string | number>) => (vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s)

/** English, or Gujarati where there is a translation, with values filled in. */
export function translate(lang: Lang, s: string, vars?: Record<string, string | number>): string {
  return fill(lang === 'gu' ? (GU[s] ?? s) : s, vars)
}
